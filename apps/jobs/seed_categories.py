def seed_categories(force=False):
    """
    Seed initial categories into database if empty or if force=True.
    """
    if not force and JobCategory.objects.exists():
        return JobCategory.objects.count()

    created_count = 0
    for item in INITIAL_CATEGORIES:
        obj, created = JobCategory.objects.get_or_create(
            category_type=item['category_type'],
            name=item['name'],
            defaults={
                'count_label': item.get('count_label', ''),
                'icon': item.get('icon', 'fa-solid fa-briefcase'),
                'badge_color': item.get('badge_color', 't-indigo'),
                'field_slug': item.get('field_slug', ''),
                'link_url': item.get('link_url', ''),
                'order': item.get('order', 0),
                'status': 'Active',
            }
        )
        if created:
            created_count += 1

    return JobCategory.objects.count()
